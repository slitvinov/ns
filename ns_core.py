def report(path, tau, pr, x, y, zc, U, SP, Rmax, Zmax, nbytes):
    dx = x[1] - x[0]
    dy = y[1] - y[0]
    dz = zc[1] - zc[0]
    ux, uy, uz = U[..., 0].astype(float), U[..., 1].astype(float), U[..., 2].astype(float)
    dux = np.gradient(ux, dx, axis=2)
    duy = np.gradient(uy, dy, axis=1)
    duz = np.gradient(uz, dz, axis=0)
    div = dux + duy + duz
    interior = (slice(1, -1), slice(1, -1), slice(1, -1))
    scale = SP.max() / min(dx, dy, dz)

    print(f"  wrote {path}  ({os.path.getsize(path)} B XML "
          f"+ {nbytes/1e6:.1f} MB in {len(ATTRS)} .raw files)")
    print(f"  tau={tau:.6g}  h={pr.h}  A={pr.A}  D={pr.D}")
    print(f"  box  r <= {Rmax:.4g}   |z| <= {Zmax:.4g}   l_z/l_r = {Zmax/Rmax:.3f}")
    print(f"  dividing layer at eta* = {pr.eta_star():.5f}  "
          f"(z = {pr.eta_star() * tau ** pr.D:+.5g}), just below z = 0")
    print(f"  max|u| = {SP.max():.6g}   (tau^-A = {tau**-pr.A:.6g})")
    print(f"  max|div u| / (max|u|/dx) = {np.abs(div[interior]).max()/scale:.3e}"
          "   <- discretisation only; the field is div-free by construction")


def check_scalings(pr):
    """Confirm the exponents of Sec. 3.1 numerically."""
    print("\nscaling checks (Sec. 3.1)")
    Xstar = 0.4 * pr.Xout
    print(f"  growth path z=0, r=sqrt(2 X* tau), X*={Xstar:.4g}:  "
          f"u_theta = q^-A E(X*), q = tau")
    prev = None
    print("      tau          u_theta         ratio     expected 4^A")
    for k in range(4, 12, 2):
        tau = 2.0 ** (-k)
        r = np.array([np.sqrt(2.0 * Xstar * tau)])
        z = np.array([0.0])
        _, utr, _, _, _, _, _ = cyl_fields(r, z, tau, pr)
        ut = (utr[0] * r[0]).item()
        if prev is None:
            print(f"    2^-{k:<3d} {ut:14.6g}")
        else:
            print(f"    2^-{k:<3d} {ut:14.6g}  {ut/prev:9.5f}   {2.0**(2*pr.A):12.5f}")
        prev = ut

    # radial pressure balance  d_r p = u_theta^2 / r
    tau = 2.0 ** -6
    print("  radial balance  d_r p = u_theta^2 / r   (2nd-order FD, so O(dr^2))")
    for npt in (400, 1600, 6400):
        r = np.linspace(0.05, 1.4, npt) * np.sqrt(2.0 * pr.Xout * tau)
        z = np.zeros_like(r)
        _, utr, _, p, _, _, _ = cyl_fields(r, z, tau, pr)
        ut = utr * r
        rel = (np.abs(np.gradient(p, r) - ut ** 2 / r).max()
               / np.abs(ut ** 2 / r).max())
        print(f"    {npt:5d} points   rel err = {rel:.2e}")

    # u_z(r,0) != 0 : the deliberate asymmetry of Sec. 2.1
    r0 = np.array([0.3 * np.sqrt(2.0 * pr.Xout * tau)])
    _, _, uz0, _, _, _, _ = cyl_fields(r0, np.array([0.0]), tau, pr)
    _, _, uzp, _, _, _, _ = cyl_fields(r0, np.array([+0.3 * tau ** pr.D]), tau, pr)
    _, _, uzm, _, _, _, _ = cyl_fields(r0, np.array([-0.3 * tau ** pr.D]), tau, pr)
    print(f"  u_z at eta = -0.3, 0, +0.3:  {uzm.item():+.4g}  {uz0.item():+.4g}  "
          f"{uzp.item():+.4g}   <- outflow both ways, nonzero at z=0")

    # U = V0 = 0 beyond Xout
    r1 = np.array([np.sqrt(2.0 * 1.3 * pr.Xout * tau)])
    urr, _, uz1, _, _, _, _ = cyl_fields(r1, np.array([0.2 * tau ** pr.D]), tau, pr)
    print(f"  at X = 1.3 Xout:  u_r = {(urr*r1).item():.3e}  u_z = {uz1.item():.3e}"
          "   <- purely azimuthal exterior")


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--t", type=float, default=0.9, help="time; tau = 1 - t")
    ap.add_argument("--n", type=int, default=161, help="grid points per side")
    ap.add_argument("--h", type=float, default=0.01, help="the exponent h < 1/100")
    ap.add_argument("--Xout", type=float, default=0.12,
                    help="edge of the poloidal region in X; sets the l_z/l_r "
                         "aspect of the plotted box")
    ap.add_argument("--Xe", type=float, default=0.12, help="swirl core width in X")
    ap.add_argument("--Xmax", type=float, default=None,
                    help="box edge in X (default 1.6*Xout). With Xout pushed well "
                         "outside the box and Xe small, inflow persists to the frame "
                         "edge and u_theta/u_r ~ (1+2X/Xe)^-(1+h) varies strongly "
                         "across it: nearly radial outside, tight helices inside.")
    ap.add_argument("--Ce", type=float, default=1.0, help="swirl amplitude")
    ap.add_argument("--eta0", type=float, default=0.14,
                    help="thickness of the u_z sign change in eta; u_r ~ g'(eta), so a "
                         "thin layer confines the inflow to a sheet at z~0 while a thick "
                         "one spreads it over the core height")
    ap.add_argument("--eta1", type=float, default=0.55, help="axial extent of the jet in eta")
    ap.add_argument("--bias", type=float, default=0.16, help="upward bias so u_z(r,0) != 0")
    ap.add_argument("--Cpsi", type=float, default=1.0,
                    help="poloidal (streamfunction) amplitude; Ce/Cpsi large is "
                         "the swirl-dominated regime Re_theta >> Re_r of Sec. 3.1")
    ap.add_argument("-o", "--out", default=None,
                    help="path to the .xdmf2 file; .raw companions sit beside it")
    ap.add_argument("--series", action="store_true",
                    help="a temporal collection, t = 0.5 .. 0.96875")
    ap.add_argument("--no-checks", action="store_true")
    a = ap.parse_args()

    pr = Profiles(h=a.h, Xout=a.Xout, Xe=a.Xe, Ce=a.Ce, Cpsi=a.Cpsi,
                  eta0=a.eta0, eta1=a.eta1, bias=a.bias)
    xf = (a.Xmax / a.Xout) if a.Xmax else 1.6

    if a.series:
        out = a.out or "out/series.xdmf2"
        build_series(out, [1.0 - 2.0 ** -k for k in range(1, 6)], pr, n=a.n,
                     Xmax_fac=xf)
    else:
        out = a.out or f"out/core_t{a.t:.3f}.xdmf2"
        build_xdmf(out, 1.0 - a.t, pr, n=a.n, Xmax_fac=xf, tval=a.t)

    if not a.no_checks:
        check_scalings(pr)


